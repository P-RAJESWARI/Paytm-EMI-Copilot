"""Tests for GET /health and the correlation ID middleware around it."""

import json

import pytest
from fastapi.testclient import TestClient

from emi_copilot.config.settings import ApplicationSettings
from emi_copilot.main import create_application

FIXED_GENERATED_CORRELATION_ID = "01JD0000000000000000000GEN"
CALLER_CORRELATION_ID = "01JD00000000000000000CALLR"


class FixedIdGenerator:
    """Test double that always returns the same identifier so assertions are exact."""

    def new_id(self) -> str:
        """Returns the fixed identifier."""
        return FIXED_GENERATED_CORRELATION_ID


@pytest.fixture
def test_client() -> TestClient:
    """Builds the application with default settings and a deterministic ID generator."""
    application = create_application(ApplicationSettings(), id_generator=FixedIdGenerator())
    return TestClient(application)


def test_get_health_returns_200_with_status_ok(test_client: TestClient) -> None:
    """The liveness endpoint answers ok without touching any dependency."""
    response = test_client.get("/health")
    assert response.status_code == 200
    assert response.json() == {"status": "ok"}


def test_get_health_with_correlation_id_header_echoes_it(test_client: TestClient) -> None:
    """A valid caller-supplied correlation ID is returned unchanged."""
    response = test_client.get("/health", headers={"X-Correlation-Id": CALLER_CORRELATION_ID})
    assert response.headers["X-Correlation-Id"] == CALLER_CORRELATION_ID


def test_get_health_without_correlation_id_header_generates_one(test_client: TestClient) -> None:
    """A missing correlation ID is generated by the injected IdGenerator and echoed."""
    response = test_client.get("/health")
    assert response.headers["X-Correlation-Id"] == FIXED_GENERATED_CORRELATION_ID


@pytest.mark.parametrize(
    "invalid_correlation_id",
    ["short", "has spaces in it", "x" * 65, "semi;colon-injection", "new\\nline-attempt"],
)
def test_get_health_with_invalid_correlation_id_header_replaces_it(
    test_client: TestClient, invalid_correlation_id: str
) -> None:
    """Malformed or oversized correlation IDs are replaced with a generated one."""
    response = test_client.get("/health", headers={"X-Correlation-Id": invalid_correlation_id})
    assert response.status_code == 200
    assert response.headers["X-Correlation-Id"] == FIXED_GENERATED_CORRELATION_ID


def test_get_health_logs_completed_request_with_its_correlation_id(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """The request-completed event is JSON and carries the request's correlation ID."""
    application = create_application(ApplicationSettings(), id_generator=FixedIdGenerator())
    TestClient(application).get("/health", headers={"X-Correlation-Id": CALLER_CORRELATION_ID})
    log_lines = [json.loads(line) for line in capsys.readouterr().out.splitlines()]
    completed_request_lines = [line for line in log_lines if line["message"] == "request completed"]
    assert len(completed_request_lines) == 1
    assert completed_request_lines[0]["correlation_id"] == CALLER_CORRELATION_ID
    assert completed_request_lines[0]["http_path"] == "/health"
    assert completed_request_lines[0]["http_status_code"] == 200


def test_get_health_with_invalid_correlation_id_logs_replacement_warning(
    capsys: pytest.CaptureFixture[str],
) -> None:
    """Replacing a bad header is logged under the new ID, without echoing the bad value."""
    application = create_application(ApplicationSettings(), id_generator=FixedIdGenerator())
    TestClient(application).get("/health", headers={"X-Correlation-Id": "bad value!"})
    output = capsys.readouterr().out
    warning_lines = [
        json.loads(line) for line in output.splitlines() if json.loads(line)["level"] == "WARNING"
    ]
    assert "bad value!" not in output
    assert warning_lines[0]["correlation_id"] == FIXED_GENERATED_CORRELATION_ID
